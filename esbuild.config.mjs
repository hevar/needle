import esbuild from "esbuild";
import path from "node:path";
import { builtinModules } from "node:module";
import process from "node:process";

const banner = `/*
Needle, an Obsidian plugin. This file is generated by esbuild; the source is in src/.
*/
`;

const production = process.argv[2] === "production";

/**
 * Bundles `inline-worker:<path>` imports as a separate script and exposes its
 * source as a string, so the worker ships inside main.js.
 */
const inlineWorker = {
	name: "inline-worker",
	setup(build) {
		build.onResolve({ filter: /^inline-worker:/ }, (args) => ({
			path: path.resolve(args.resolveDir, args.path.slice("inline-worker:".length)),
			namespace: "inline-worker",
		}));
		build.onLoad({ filter: /.*/, namespace: "inline-worker" }, async (args) => {
			const result = await esbuild.build({
				entryPoints: [args.path],
				bundle: true,
				write: false,
				format: "iife",
				target: "es2021",
				minify: production,
				sourcemap: production ? false : "inline",
				metafile: true,
				logLevel: "silent",
			});
			return {
				contents: `export default ${JSON.stringify(result.outputFiles[0].text)};`,
				loader: "js",
				watchFiles: Object.keys(result.metafile.inputs).map((input) => path.resolve(input)),
			};
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/*",
		"@lezer/*",
		...builtinModules,
		...builtinModules.map((name) => `node:${name}`),
	],
	format: "cjs",
	target: "es2021",
	logLevel: "info",
	sourcemap: production ? false : "inline",
	treeShaking: true,
	minify: production,
	outfile: "main.js",
	plugins: [inlineWorker],
});

if (production) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
